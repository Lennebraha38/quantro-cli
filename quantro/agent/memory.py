FALLBACK_PRICING = {"input": 1.00, "output": 3.00}


class MemoryManager:
    """Manages project memory, system prompts, token analytics, and context compacting."""

    def __init__(self, project_root: Any):
        self.project_root = (Path(project_root) if project_root else Path.cwd()).resolve()

    def calculate_cost(self, model: str, prompt_tokens: int, completion_tokens: int) -> float:
        pricing = MODEL_PRICING.get(model, FALLBACK_PRICING)
        return (prompt_tokens / 1_000_000 * pricing["input"]) + (completion_tokens / 1_000_000 * pricing["output"])

    def read_project_memory(self) -> Optional[str]:
        target = self.project_root / "QUANTRO.md"
        if target.exists() and target.is_file():
            try:
                return target.read_text(encoding="utf-8")
            except Exception:
                return None
        return None

    def initialize_project_memory(self) -> str:
        target = self.project_root / "QUANTRO.md"
        files = [p.name for p in self.project_root.iterdir() if not p.name.startswith(".")]

        languages = []
        if any(f.endswith(".py") or f in ("pyproject.toml", "setup.py") for f in files):
            languages.append("Python")
        if any(f.endswith((".ts", ".js")) or f == "package.json" for f in files):
            languages.append("TypeScript/JavaScript")
        if "Cargo.toml" in files:
            languages.append("Rust")
        if "go.mod" in files:
            languages.append("Go")
        if not languages:
            languages.append("General Polyglot")

        content = f"""# QUANTRO.md — Repository Architecture & Memory Guide

## Project Identity
- **Repository:** {self.project_root.name}
- **Root Path:** {self.project_root}
- **Detected Stacks:** {", ".join(languages)}
- **Agent Architecture:** OpenCode 2.0 / Quantro Engine

## Architecture Guidelines
- Modular components with clean separation of concerns.
- Always read existing files before modifying to adhere to exact patterns.
- Ensure all tests pass prior to marking tasks completed.

---
*Generated by Quantro 2.0 (`/init`). Update this file to retain persistent project rules.*
"""
        target.write_text(content, encoding="utf-8")
        return str(target)

    def build_system_prompt(self, role_key: str = "build") -> str:
        role_info = ROLE_DEFINITIONS.get(role_key, ROLE_DEFINITIONS["build"])
        base_prompt = role_info["prompt"]

        sys_content = f"""{base_prompt}

Current Repository Root: {self.project_root}
Environment: Linux Terminal / OpenCode 2.0 Autonomous Engine

Operational Rules:
- NEVER use placeholder code (`TODO`, `pass`, `...`). Write 100% complete, working code.
- Always inspect code first with `read_file` before making modifications with `edit_file` or `multi_edit`.
- For research and deep multi-file lookups, delegate using `dispatch_agent` to keep main context clean.
- Verify modifications with tests or syntax checks via `run_bash` where applicable.
"""
        project_mem = self.read_project_memory()
        if project_mem:
            sys_content += f"\n--- [REPOSITORY MEMORY: QUANTRO.md] ---\n{project_mem}\n--- [END REPOSITORY MEMORY] ---\n"

        return sys_content

    def prune_tool_outputs(self, messages: List[Dict[str, Any]]) -> int:
        """
        Prunes large outputs from older tool calls (leaving the last 4 messages intact).
        Returns number of pruned tool messages.
        """
        if len(messages) <= 6:
            return 0

        pruned_count = 0
        older = messages[:-4]
        for msg in older:
            if msg.get("role") == "tool":
                content = msg.get("content", "")
                if isinstance(content, str) and len(content) > 300:
                    msg["content"] = content[:150] + f"\n... [Output pruned: {len(content)} chars to save context]"
                    pruned_count += 1
        return pruned_count

    def compact_messages(self, messages: List[Dict[str, Any]]) -> tuple[List[Dict[str, Any]], int]:
        """Compresses older message history into structured summary."""
        if len(messages) <= 4:
            return messages, 0

        initial_len = len(messages)
        recent = messages[-4:]
        older = messages[:-4]

        summaries = []
        for msg in older:
            role = msg.get("role", "")
            content = msg.get("content", "")
            if isinstance(content, str) and content.strip():
                summaries.append(f"- [{role}]: {content.strip()[:80]}...")
            elif msg.get("tool_calls"):
                for tc in msg["tool_calls"]:
                    fn = tc.get("function", {}).get("name", "tool")
                    summaries.append(f"- [tool]: {fn}")

        summary_text = (
            "[SYSTEM MEMORY AUTO-COMPACTED SUMMARY]\n"
            + "\n".join(summaries[-15:])
            + "\n[END AUTO-COMPACTED SUMMARY]"
        )

        compacted = [{"role": "system", "content": summary_text}] + recent
        pruned_count = initial_len - len(compacted)
        return compacted, pruned_count

    def check_and_auto_compact(self, session) -> bool:
        """Automatically prunes and compacts session if tokens exceed configured threshold."""
        if not config_manager.auto_compact_enabled:
            return False

        threshold = config_manager.auto_compact_threshold
        if session.total_tokens >= threshold:
            # 1. Prune old tool outputs
            self.prune_tool_outputs(session.messages)
            # 2. Compact history
            compacted, pruned = self.compact_messages(session.messages)
            session.messages = compacted
            return True
        return False
